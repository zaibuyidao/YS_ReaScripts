local selitem = reaper.CountSelectedMediaItems(0)
local selitem_idx = 0
local PCS = {}
PCS_sort = {}
while selitem_idx < selitem do
    local MediaItem = reaper.GetSelectedMediaItem(0, selitem_idx)
    local take = reaper.GetActiveTake(MediaItem)
    reaper.MIDI_DisableSort(take)
    local retval, notecnt, ccevtcnt, textsyxevtcnt = reaper.MIDI_CountEvts(take)
    for ccidx = 0, ccevtcnt - 1 do
        local retval, selected, muted, ppqpos_pc, chanmsg, chan, pcnum, msg3 = reaper.MIDI_GetCC(take, ccidx)
        if chanmsg == 192 then
            local retval, selected, muted, ppqpos_32, chanmsg_32, chan, msg2_32, msg3_32 = reaper.MIDI_GetCC(take, ccidx - 1)
            local retval, selected, muted, ppqpos_0, chanmsg_0, chan, msg2_0, msg3_0 = reaper.MIDI_GetCC(take, ccidx - 2)
            if (chanmsg_32 == 176 and msg2_32 == 32) and (chanmsg_0 == 176 and msg2_0 == 0) then
                PCS[msg3_0 .. ',' .. msg3_32 .. ',' .. pcnum] = PCS[msg3_0 .. ',' .. msg3_32 .. ',' .. pcnum] or {}
                table.insert(PCS[msg3_0 .. ',' .. msg3_32 .. ',' .. pcnum], ppqpos_pc)
            end
        end
    end
    selitem_idx = selitem_idx + 1
end

local tablelen = 0
for i, v in pairs(PCS) do
    tablelen = tablelen + 1
    table.insert(PCS_sort, {
        instnum = i,
        pos = v[1]
    })
end

table.sort(PCS_sort, function(a, b)
    return a.pos < b.pos
end)

local list = ''

if tablelen > 0 then
    for i, v in ipairs(PCS_sort) do
        if tb_ins[v.instnum] == nil then
            a, b, pcnum = string.match(v.instnum, '(%d+),(%d+),(%d+)')
            tb_ins[v.instnum] = GM_map[tonumber(pcnum)]
        end
        list = list .. ' & ' .. tb_ins[v.instnum]
    end
end
